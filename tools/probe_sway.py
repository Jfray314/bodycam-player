"""Fit viewmodel sway inputs, camera roll, lean and stress idle alpha to the UE4SS probe recordings -> assets/sway_reference.json.

Usage: python -I tools/probe_sway.py [probe_dir] [out.json]   (default extracted/probe, assets/sway_reference.json)
Needs numpy. Findings (what the recordings do and do not contain):
- ABP_Procedural_Sway_C SpringSway nodes expose only INPUTS and the (switching) table parameters, not their spring state or
  output. Inputs: nodes 9,8,5 InputValue == LookDeltaInput.X, nodes 7,6 == LookDeltaInput.Y, nodes 4,3,2 == strafe axis and
  nodes 1,0 == forward axis (+-1). The per-node tables switch instantly with IsAiming (hip: HipLook*, aim: Look*).
  So the spring output itself can't be fitted; only the input chain is.
- LookDeltaInput = 0.4777 * (control rotation rate deg/s) / 60, one frame late (ABP runs before the controller update).
  AC_BodycamCamera.Yaw(DeltaTime) = 0.00796 * yaw rate deg/s with no lag.
- Camera roll (cam_roll) = FInterp(~1.8) of strafe(+-5) + 2.6 * look-rate term, lean = cascade FInterp 12 -> 8 (-> 2 for roll).
- Final camera does not show ADS blend or sway (the camera is not hung on the arms in ADS) -> ADS alpha timing isn't observable.
"""
import csv, json, os, sys
import numpy as np

PROBE = sys.argv[1] if len(sys.argv) > 1 else 'extracted/probe'
OUT = sys.argv[2] if len(sys.argv) > 2 else 'assets/sway_reference.json'
S = 'ABP_Procedural_Sway_C.'
AC = 'AC_BodycamAnimationComponent_C.'


def load(name):
    with open(os.path.join(PROBE, name + '.csv')) as f:
        rd = csv.reader(f); h = next(rd); rows = []
        for x in rd:
            if len(x) != len(h):
                continue
            row = []
            for v in x:
                try: row.append(float(v))
                except ValueError: row.append(float('nan'))
            rows.append(row)
    A = np.array(rows)
    class R: pass
    r = R(); r.ix = {c: i for i, c in enumerate(h)}; r.A = A
    r.g = lambda n: A[:, r.ix[n]]
    r.t = A[:, 0]; r.dt = np.r_[0.0138, np.diff(r.t)]
    return r


def wrap(x): return (x + 180) % 360 - 180
def fi(cur, tgt, dt, s): return cur + (tgt - cur) * min(1.0, max(0.0, dt * s))
def fseries(x, dt, s):
    y = np.zeros(len(x))
    for k in range(1, len(x)): y[k] = fi(y[k - 1], x[k], dt[k], s)
    return y
def rms(a): return float(np.sqrt(np.mean(np.square(a))))
def mr(v, a, b, c, d): return c + (d - c) * np.clip((v - a) / (b - a), 0, 1)


def nelder(f, x0, step, iters=300):
    n = len(x0); pts = [np.array(x0, float)]
    for i in range(n):
        p = np.array(x0, float); p[i] += step[i]; pts.append(p)
    vals = [f(p) for p in pts]
    for _ in range(iters):
        o = np.argsort(vals); pts = [pts[i] for i in o]; vals = [vals[i] for i in o]
        c = np.mean(pts[:-1], 0); xr = c + (c - pts[-1]); fr = f(xr)
        if fr < vals[0]:
            xe = c + 2 * (c - pts[-1]); fe = f(xe)
            pts[-1], vals[-1] = (xe, fe) if fe < fr else (xr, fr)
        elif fr < vals[-2]: pts[-1], vals[-1] = xr, fr
        else:
            xc = c + 0.5 * (pts[-1] - c); fc = f(xc)
            if fc < vals[-1]: pts[-1], vals[-1] = xc, fc
            else:
                for i in range(1, n + 1): pts[i] = pts[0] + 0.5 * (pts[i] - pts[0]); vals[i] = f(pts[i])
    o = int(np.argmin(vals)); return pts[o], vals[o]


def resample(r, cols, t0, t1, hz=60):
    tt = np.arange(t0, t1, 1.0 / hz)
    return {k: [round(float(v), 4) for v in np.interp(tt, r.t, c)] for k, c in cols.items()}


def body(r):
    yaw = np.radians(r.g('ctl_yaw')); vx, vy = r.g('vel_x'), r.g('vel_y')
    return vx * np.cos(yaw) + vy * np.sin(yaw), -vx * np.sin(yaw) + vy * np.cos(yaw)


out = {'note': 'generated by tools/probe_sway.py from extracted/probe/rec_*.csv (UE4SS recordings of the real game)'}

# 1. look input chain: LookDeltaInput / Yaw(DeltaTime) vs control rotation rate
look = {}
for name in ('rec_1791597881', 'rec_1791598187', 'rec_1791598198'):
    r = load(name); res = {}
    for ax, col, sw, ldi in (('yaw', 'ctl_yaw', 1, 'LookDeltaInput.X'), ('pitch', 'ctl_pitch', 1, 'LookDeltaInput.Y')):
        d = np.r_[0, wrap(np.diff(r.g(col)))]; rate = d / r.dt
        y = r.g(S + ldi)
        for lag in (0, 1):
            x = np.r_[np.zeros(lag), (rate / 60)[:len(rate) - lag]]
            c = float((x @ y) / (x @ x))
            res[f'{ax}_lag{lag}'] = {'gain': round(c, 4), 'corr': round(float(np.corrcoef(x, y)[0, 1]), 4), 'rms': round(rms(c * x - y), 3), 'sd': round(rms(y), 3)}
    yd = r.g('AC_BodycamCamera_C.Yaw(DeltaTime)'); d = np.r_[0, wrap(np.diff(r.g('ctl_yaw')))] / r.dt
    res['yaw_delta_time'] = {'per_deg_s': round(float((d @ yd) / (d @ d)), 5), 'corr': round(float(np.corrcoef(d, yd)[0, 1]), 4)}
    look[name] = res
lw = []
for name in ('rec_1791597881', 'rec_1791598187'):
    r = load(name)
    cols = {'ctl_yaw': np.unwrap(np.radians(r.g('ctl_yaw'))) * 180 / np.pi, 'ldi_x': r.g(S + 'LookDeltaInput.X')}
    lw.append(resample(r, cols, 1.0, min(float(r.t[-1]), 9.0)))
out['look_input'] = {'series_60hz': lw, 'ldi_per_deg_s_over_60': 0.4777, 'ldi_lag_frames': 1, 'yaw_delta_time_per_deg_s': 0.00796, 'clamp_max_pin': 10.0, 'fits': look}

# 2. node inputs: movement axes
r = load('rec_1791597900'); fwd, right = body(r); cr = r.g('crouched')
mv = {}
for lab, node, sig in (('strafe', 4, right), ('forward', 1, fwd)):
    t = r.g(f'{S}AnimGraphNode_SpringSway_{node}.InputValue')
    best = min(((rms(fseries(np.clip(sig / k, -1, 1), r.dt, s) - t), k, s) for k in (20, 50, 100, 125) for s in (20, 30, 50)))
    mv[lab] = {'node': node, 'rms': round(best[0], 3), 'vel_for_full_cm_s': best[1], 'interp_speed': best[2]}
out['move_input'] = {'fits': mv, 'note': 'InputValue is ~+-1 whenever walking/sprinting/crouch-walking (saturates by ~0.5 m/s)'}

# 3. camera roll: FInterp(s)[5*strafe + g*map(Yaw(DeltaTime), -3..3 -> 8..-8)] on yaw-only windows
def roll_prep(name, win):
    r = load(name); fwd, right = body(r)
    r.mx = np.clip(right / np.where(r.g('crouched') > 0.5, 100.0, 125.0), -1, 1)
    r.yd = r.g('AC_BodycamCamera_C.Yaw(DeltaTime)'); r.roll = r.g('cam_roll')
    r.mask = win(r.t) & (np.abs(wrap(r.g('ctl_pitch'))) < 30)
    return r
rolls = {
    'rec_1791597900': roll_prep('rec_1791597900', lambda t: (t < 11) | ((t > 32) & (t < 40))),
    'rec_1791597881': roll_prep('rec_1791597881', lambda t: t > 0),
    'rec_1791598187': roll_prep('rec_1791598187', lambda t: t > 0),
}
def roll_pred(p, r, single=True):
    s, gl, gs, b = p
    tgt = gs * 5 * r.mx + gl * np.interp(r.yd, [-3, 3], [8, -8])
    return b + fseries(tgt, r.dt, abs(s))
def roll_cost(p): return rms(np.concatenate([(roll_pred(p, r) - r.roll)[r.mask] for r in rolls.values()]))
before = {k: round(rms((roll_pred([8, 1, 1, 0], r) - r.roll)[r.mask]), 3) for k, r in rolls.items()}
best = min((nelder(roll_cost, [s0, 1, 1, 0], [1, .3, .3, .3]) for s0 in (1.5, 3, 6)), key=lambda x: x[1])
p = best[0]
after = {k: round(rms((roll_pred(p, r) - r.roll)[r.mask]), 3) for k, r in rolls.items()}
series = {}
for k, r in rolls.items():
    # contiguous masked windows resampled to 60 Hz (yaw unwrapped so rates survive interpolation)
    idx = np.where(r.mask)[0]; ranges = []; s0 = idx[0]
    for a, b in zip(idx[:-1], idx[1:]):
        if b - a > 3: ranges.append((r.t[s0], r.t[a])); s0 = b
    ranges.append((r.t[s0], r.t[idx[-1]]))
    ranges = [x for x in ranges if x[1] - x[0] > 1.0]
    cols = {'ctl_yaw': np.unwrap(np.radians(r.g('ctl_yaw'))) * 180 / np.pi, 'move_x': r.mx, 'cam_roll': r.roll}
    series[k] = [resample(r, cols, t0, t1) | {'t0': round(float(t0), 3)} for t0, t1 in ranges]
out['roll'] = {
    'model': 'roll = FInterp(speed)[ strafe_gain*5*move_x + look_gain*map(Yaw(DeltaTime), -3..3 -> 8..-8) ]  (UE deg, cw+)',
    'speed': round(abs(float(p[0])), 3), 'look_gain': round(float(p[1]), 3), 'strafe_gain': round(float(p[2]), 3), 'bias': round(float(p[3]), 3),
    'rms_deg_before_BP_FInterp8': before, 'rms_deg_after': after, 'sd_deg': {k: round(rms(r.roll[r.mask] - r.roll[r.mask].mean()), 3) for k, r in rolls.items()},
    'series_60hz': series}

# 4. lean: NormalizedLean (+-15), camera right offset (cm) and roll (deg) vs a step at the first key press
r = load('rec_1791598355'); t = r.t
nl = r.g('ABP_Procedural_AimOffset_C.NormalizedLean') / 15
yaw = np.radians(r.g('ctl_yaw')); dx = r.g('cam_x') - r.g('pawn_x'); dy = r.g('cam_y') - r.g('pawn_y')
camr = -dx * np.sin(yaw) + dy * np.cos(yaw); roll = r.g('cam_roll'); m = (t > 0.6) & (t < 2.7)
def chain(speeds, tp):
    y = np.where(t >= tp, -1.0, 0.0)
    for s in speeds: y = fseries(y, r.dt, s)
    return y
tp = min(((rms((chain([12, 8], q) - nl)[m]), q) for q in np.arange(0.74, 0.80, 0.002)))[1]
def fitg(y, sig):
    X = np.c_[y, np.ones(len(y))]; c = np.linalg.lstsq(X[m], sig[m], rcond=None)[0]; return c, rms((X @ c - sig)[m])
lean = {'press_t': round(float(tp), 3), 'normalized_lean': {}, 'camera_right_cm': {}, 'camera_roll_deg': {}}
for sp in ([12], [12, 8], [12, 12], [12, 8, 2], [12, 2], [8, 2]):
    lean['normalized_lean'][str(sp)] = round(rms((chain(sp, tp) - nl)[m]), 4)
    c, e = fitg(chain(sp, tp), camr); lean['camera_right_cm'][str(sp)] = {'peak': round(float(abs(c[0])), 2), 'rms': round(e, 3)}
    c, e = fitg(chain(sp, tp), roll); lean['camera_roll_deg'][str(sp)] = {'peak': round(float(abs(c[0])), 2), 'rms': round(e, 3)}
lean['conclusion'] = 'Leaning Alpha FInterp 12 (BP) -> FInterp 8 = NormalizedLean and camera offset; roll = one more FInterp 2'
lean['series_60hz'] = resample(r, {'normalized_lean': nl, 'camera_right_cm': camr, 'cam_roll': roll}, tp - 0.05, tp + 2.0) | {'press_offset_s': 0.05}
out['lean'] = lean

# 5. ADS / stress
r = load('rec_1791597946'); ia = r.g(S + 'IsAiming'); sw = np.where(np.diff(ia) != 0)[0] + 1
ads = {'is_aiming_latency': 'IsAiming flips on the key frame; node AdsScale pins switch the same frame (no ramp)',
       'sway_node_pins': {'hip_AdsScale_Y_Z': [round(float(np.median(r.g(S + 'MagnifiedADSScale.Y')[ia == 0])), 4), round(float(np.median(r.g(S + 'MagnifiedADSScale.Z')[ia == 0])), 4)],
                          'aim_AdsScale_Y_Z': [round(float(np.median(r.g(S + 'AnimGraphNode_SpringSway_9.AdsScale')[ia == 1])), 4), round(float(np.median(r.g(S + 'AnimGraphNode_SpringSway_7.AdsScale')[ia == 1])), 4)],
                          'rot_pins_constant': [round(float(np.median(r.g(S + f'AnimGraphNode_SpringSway_{n}.AdsScale'))), 3) for n in (8, 6, 5)],
                          'note': 'aim pin = table AdsScale (3, 2 for M4A1 pos y/z) * MagnifiedADSScale; hip pin = MagnifiedADSScale'},
       'ads_speed_pin': float(np.median(r.g('ABP_Procedural_Viewmodel_C.AnimGraphNode_Ads.AdsSpeed'))),
       'additive_blend_alpha_pin': float(np.median(r.g('ABP_Procedural_Viewmodel_C.AnimGraphNode_Ads.AdditiveBlendAlpha'))),
       'camera_fov_const': float(r.g('fov').min()), 'camera_ads_blend_visible': False}
out['ads'] = ads
st = {}
for name in ('rec_1791597900', 'rec_1791597946', 'rec_1791598198'):
    r = load(name); sub = r.g(AC + 'StressedSubtleIdleAlpha'); strong = r.g(AC + 'StressedStrongIdleAlpha'); stress = r.g('WW_SurvivorStatus_C.Stress')
    ia = r.g(S + 'IsAiming'); v3 = np.sqrt(r.g('vel_x') ** 2 + r.g('vel_y') ** 2 + r.g('vel_z') ** 2)
    y = np.zeros(len(sub)); y[0] = sub[0]
    for k in range(1, len(y)): y[k] = fi(y[k - 1], 0.0 if ia[k] > .5 else mr(v3[k], 0, 100, 0.1, 1.0), r.dt[k], 10.0)
    sg = np.where(ia > .5, mr(stress, .5, 1, 0, 1), mr(stress, 0, 1, 0, 4))
    st[name] = {'subtle_rms': round(rms(y - sub), 4), 'subtle_sd': round(rms(sub - sub.mean()), 3), 'strong_rms': round(rms(sg - strong), 4), 'strong_sd': round(rms(strong - strong.mean()), 3)}
out['stress'] = {'model': 'BP Stress Tick: subtle=FInterp10(aim?0:map(|v|3D 0..100->0.1..1)); strong=aim?map(stress .5..1->0..1):map(stress 0..1->0..4)', 'fits': st}
# a compact reference series for the Rust test: speed (m/s, 3D), aiming, stress, subtle, strong
r = load('rec_1791598198'); v3 = np.sqrt(r.g('vel_x') ** 2 + r.g('vel_y') ** 2 + r.g('vel_z') ** 2) / 100
out['stress']['series_60hz'] = resample(r, {'speed_m_s': v3, 'aiming': r.g(S + 'IsAiming'), 'stress': r.g('WW_SurvivorStatus_C.Stress'),
                                            'subtle': r.g(AC + 'StressedSubtleIdleAlpha'), 'strong': r.g(AC + 'StressedStrongIdleAlpha')}, 0.5, float(r.t[-1]) - 0.1)

os.makedirs(os.path.dirname(OUT) or '.', exist_ok=True)
json.dump(out, open(OUT, 'w'), separators=(',', ':'))
print(json.dumps({k: v for k, v in out.items() if k not in ('roll', 'lean', 'stress')}, indent=1)[:3000])
print('roll', {k: v for k, v in out['roll'].items() if k != 'series_60hz'})
print('lean', {k: v for k, v in out['lean'].items() if k != 'series_60hz'})
print('stress', out['stress']['fits'])
